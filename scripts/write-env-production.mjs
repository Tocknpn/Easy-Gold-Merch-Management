// Generates .env.production from the VITE_* keys in your local .env.
// Vite loads .env.production during `vite build`, so Cloudflare/GitHub git builds
// become LIVE automatically — no dependence on Cloudflare env-var injection.
//
// SAFE TO COMMIT: only VITE_SUPABASE_URL + VITE_SUPABASE_ANON_KEY are copied.
// The anon key is public by design (it ships in the browser bundle anyway).
// The SECRET service_role key stays in .env only, never here.
//
// Run:  npm run env:production
// Then: git add .env.production && git commit -m "live build keys" && git push
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, '.env.production');

if (!fs.existsSync(envPath)) {
  console.error('No .env found. Fill in .env first (see .env.example).');
  process.exit(1);
}

const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/);
const kept = lines
  .map((l) => l.trim())
  .filter((l) => l.startsWith('VITE_') && l.includes('='))
  .map((l) => l.replace(/^VITE_/, 'VITE_')); // keep as-is

if (!kept.some((l) => l.startsWith('VITE_SUPABASE_URL=')) || !kept.some((l) => l.startsWith('VITE_SUPABASE_ANON_KEY='))) {
  console.error('.env is missing VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY.');
  process.exit(1);
}

const header = [
  '# Auto-generated by scripts/write-env-production.mjs — run `npm run env:production` to refresh.',
  '# Commit this file: it contains only PUBLIC keys (anon + project URL).',
  '# Vite loads this during `vite build`, making Cloudflare/GitHub builds LIVE.',
  '# NEVER put SUPABASE_SERVICE_ROLE_KEY or passwords here.',
  '',
].join('\n');

fs.writeFileSync(outPath, header + kept.join('\n') + '\n', 'utf8');
console.log('Wrote .env.production with:\n  ' + kept.map((l) => l.split('=')[0]).join('\n  '));
console.log('\nNext:  git add .env.production && git commit -m "live build keys" && git push');